export const getInstitutionTypeForLevel = (educationLevel) => {
  if (
    [
      "class_7",
      "class_8",
      "class_9",
      "class_10",
      "class_11",
      "class_12",
    ].includes(educationLevel)
  ) {
    return "board";
  }

  if (educationLevel === "diploma") {
    return "institution";
  }

  if (
    ["bachelors", "masters", "mba", "phd"].includes(
      educationLevel,
    )
  ) {
    return "university";
  }

  if (educationLevel === "other") {
    return "other";
  }

  return "";
};

export const getInstitutionOptions = (educationLevel) => {
  const type = getInstitutionTypeForLevel(educationLevel);

  if (type === "board") return BOARD_OPTIONS;
  if (type === "institution") return DIPLOMA_INSTITUTIONS;
  if (type === "university") return UNIVERSITY_OPTIONS;

  return [];
};

export const getProgramOptions = (educationLevel) =>
  PROGRAMS_BY_LEVEL[educationLevel] || [];

export const getStreamOptions = (
  educationLevel,
  programChoice,
) => {
  if (STREAMS_BY_LEVEL[educationLevel]) {
    return STREAMS_BY_LEVEL[educationLevel];
  }

  return STREAMS_BY_PROGRAM[programChoice] || [];
};

export const levelUsesProgram = (educationLevel) =>
  [
    "diploma",
    "bachelors",
    "masters",
    "mba",
    "phd",
    "other",
  ].includes(educationLevel);

export const levelUsesStream = (educationLevel) =>
  ["class_11", "class_12"].includes(
    educationLevel,
  ) || levelUsesProgram(educationLevel);