export const getInstitutionsForState = (
  state,
  educationLevel,
) => {
  if (!state) return [];

  return INDIA_INSTITUTIONS.filter((item) => {
    if (item.state !== state) return false;

    if (educationLevel === "diploma") {
      return item.category === "diploma";
    }

    return item.category !== "diploma";
  });
};

export const findInstitutionById = (institutionId) =>
  INDIA_INSTITUTIONS.find(
    (item) => item.id === institutionId,
  ) || null;